CREATE TABLE store.shopping_cart (
     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

     user_id BIGINT NOT NULL UNIQUE,

     CONSTRAINT fk_cart_user
             FOREIGN KEY (user_id)
             REFERENCES store.users(id)
);

CREATE TABLE store.cart_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    cart_id BIGINT NOT NULL,

    product_id BIGINT NOT NULL,

    quantity INTEGER NOT NULL,

    CONSTRAINT fk_cart_item_cart
            FOREIGN KEY (cart_id)
            REFERENCES store.shopping_cart(id)
            ON DELETE CASCADE,

    CONSTRAINT fk_cart_item_product
            FOREIGN KEY (product_id)
            REFERENCES store.product(id),

    CONSTRAINT chk_cart_item_quantity
            CHECK (quantity >= 1),

    CONSTRAINT uk_cart_item_product
            UNIQUE (cart_id, product_id)
);